import { Product, ProductVariant, ColorOption, SizeCode } from '@/types';

// Helper to create product variants
function createVariants(
  productId: string,
  colors: ColorOption[],
  sizes: SizeCode[],
  price: number,
  originalPrice?: number
): ProductVariant[] {
  const variants: ProductVariant[] = [];
  colors.forEach((c, cIdx) => {
    sizes.forEach((s, sIdx) => {
      variants.push({
        id: `${productId}-${c.slug}-${s.toLowerCase()}`,
        sku: `${productId.toUpperCase()}-${c.slug.toUpperCase()}-${s}`,
        color: c,
        size: s,
        price,
        originalPrice,
        stock: 12 + ((cIdx + sIdx * 5) % 35),
      });
    });
  });
  return variants;
}

