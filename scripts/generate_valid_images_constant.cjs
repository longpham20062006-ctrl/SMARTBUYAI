const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const IMAGE_DIR = path.join(ROOT_DIR, 'public', 'images', 'san-pham');
const TARGET_FILE = path.join(ROOT_DIR, 'src', 'constants', 'validImagePaths.ts');

function getAllFiles(dir, list = []) {
  if (!fs.existsSync(dir)) return list;
  for (const f of fs.readdirSync(dir)) {
    const full = path.join(dir, f);
    if (fs.statSync(full).isDirectory()) {
      getAllFiles(full, list);
    } else if (/\.(webp|jpg|jpeg|png|avif)$/i.test(f)) {
      const rel = full.substring(path.join(ROOT_DIR, 'public').length).split(path.sep).join('/');
      const webPath = rel.startsWith('/') ? rel : '/' + rel;
      list.push(webPath);
    }
  }
  return list;
}

const images = getAllFiles(IMAGE_DIR);
images.sort();

console.log('Total real disk images scanned:', images.length);

const content = `/**
 * SMARTBUY AI — REAL DISK PRODUCT IMAGES WHITELIST
 * Auto-generated by scripts/generate_valid_images_constant.cjs
 * Contains exactly ${images.length} verified real images on disk in public/images/san-pham/
 */

export const REAL_DISK_IMAGE_PATHS: string[] = ${JSON.stringify(images, null, 2)};

export const REAL_DISK_IMAGE_PATHS_SET: Set<string> = new Set(
  REAL_DISK_IMAGE_PATHS.map((p) => p.toLowerCase())
);
`;

fs.writeFileSync(TARGET_FILE, content, 'utf-8');
console.log('Wrote', TARGET_FILE, 'successfully with', images.length, 'entries.');

